# --- Клиент DeepSeek ---
DEEPSEEK_BASE_URL = "https://api.zveno.ai/v1"
DEEPSEEK_MODEL = "deepseek/deepseek-v4.1-flash"

http_timeout = httpx.Timeout(
    timeout=60.0,
    connect=15.0,
    read=30.0,
    write=10.0,
)

ai_client = AsyncOpenAI(
    api_key=DEEPSEEK_API_KEY,
    base_url=DEEPSEEK_BASE_URL,
    http_client=httpx.AsyncClient(timeout=http_timeout),
    max_retries=2,
)


async def ask_ai(prompt: str, system: str = "Ты — терпеливый репетитор. Объясняй максимально кратко, по делу, на русском. Не используй формулы так как они не видны в телеграмме.") -> str:
    """Запрос к DeepSeek с обработкой ошибок."""
    try:
        resp = await ai_client.chat.completions.create(
            model=DEEPSEEK_MODEL,
            messages=[
                {"role": "system", "content": system},
                {"role": "user", "content": prompt},
            ],
            temperature=0.7,
            max_tokens=800,  # Увеличиваем лимит, чтобы модель не обрывалась на полуслове
        )

        # Безопасно достаем текст
        content = resp.choices[0].message.content
        if content:
            return content.strip()
        else:
            return "❌ ИИ вернул пустой ответ. Попробуй переформулировать тему."

    except APITimeoutError:
        logging.warning("DeepSeek: таймаут")
        return "⏳ Сервер ИИ не ответил вовремя. Попробуй ещё раз через минуту."
    except APIConnectionError:
        logging.warning("DeepSeek: ошибка соединения")
        return "📡 Не удалось соединиться с сервером ИИ. Проверь интернет."
    except APIStatusError as e:
        logging.error(f"DeepSeek статус {e.status_code}: {e.message}")
        return "⚠️ Сервис ИИ временно недоступен. Попробуй позже."
    except Exception as e:
        logging.error(f"Неизвестная ошибка ИИ: {e}")
        return "❌ Не удалось получить ответ от ИИ. Попробуй позже."


