@dp.callback_query(F.data.startswith("ans:"))
async def on_answer_cb(cb: CallbackQuery, state: FSMContext):
    data = await state.get_data()
    if "current_card_idx" not in data or "exam" not in data:
        await cb.answer("Карточка устарела, начни заново.")
        return

    exam, subj, tid = data["exam"], data["subject"], data["topic"]
    idx = data["current_card_idx"]
    card = TOPICS[exam][subj][tid]["cards"][idx]

    val = cb.data.split(":")[1]
    if val == "skip":
        await cb.answer("Пропущено")
        await process_answer(cb.bot, state, correct=False, user_answer=None, quality=0)
        return

    if "options" not in card:
        await cb.answer("Ответь текстом 👇")
        return

    chosen = card["options"][int(val)]
    correct = chosen.strip().lower() == card["answer"].strip().lower()
    quality = 4 if correct else 1
    await cb.answer("✅ Правильно" if correct else "❌ Неверно")
    await process_answer(cb.bot, state, correct=correct, user_answer=chosen, quality=quality)


