PENDING_REMINDERS = []  # отложенные напоминания: [{user_id, chat_id, exam, subject, topic, send_at}, ...]
def schedule_reminder(user_id: int, chat_id: int, exam: str, subject: str, topic: str, delay_seconds: int = 180):
    """Запланировать напоминание по теме. Если уже есть — заменить."""
    global PENDING_REMINDERS
    PENDING_REMINDERS = [
        r for r in PENDING_REMINDERS
        if not (r["user_id"] == user_id and r["exam"] == exam and r["subject"] == subject and r["topic"] == topic)
    ]
    send_at = datetime.now() + timedelta(seconds=delay_seconds)
    PENDING_REMINDERS.append({
        "user_id": user_id,
        "chat_id": chat_id,
        "exam": exam,
        "subject": subject,
        "topic": topic,
        "send_at": send_at,
    })
    logging.info(f"⏰ Напоминание для {user_id} через {delay_seconds}с: {exam}/{subject}/{topic}")


async def send_reminder(bot: Bot, r: dict):
    exam, subj, tid = r["exam"], r["subject"], r["topic"]
    if exam not in TOPICS or subj not in TOPICS[exam] or tid not in TOPICS[exam][subj]:
        return
    title = TOPICS[exam][subj][tid]["title"]
    kb = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🎴 Проверить себя", callback_data=f"review:{exam}:{subj}:{tid}")],
        [InlineKeyboardButton(text="⏰ Напомнить позже", callback_data=f"snooze:{exam}:{subj}:{tid}")],
    ])
    try:
        await bot.send_message(
            chat_id=r["chat_id"],
            text=(
                f"🔔 <b>Пора повторить!</b>\n\n"
                f"Ты недавно прошёл тему:\n<b>{title}</b>\n\n"
                "Сейчас хороший момент проверить, как усвоился материал. Готов?"
            ),
            parse_mode="HTML",
            reply_markup=kb,
        )
    except Exception as e:
        logging.error(f"Не удалось отправить напоминание: {e}")


async def reminder_worker(bot: Bot):
    """Фоновая задача: раз в 20 секунд проверяет и отправляет напоминания."""
    logging.info("Reminder worker запущен")
    while True:
        try:
            now = datetime.now()
            to_send = [r for r in PENDING_REMINDERS if r["send_at"] <= now]
            for r in to_send:
                PENDING_REMINDERS.remove(r)
                await send_reminder(bot, r)
        except Exception as e:
            logging.error(f"Ошибка reminder worker: {e}")
        await asyncio.sleep(20)
