def sm2_update(st: dict, quality: int) -> dict:
    if quality < 3:
        st["rep"] = 0
        st["interval"] = 1.0
    else:
        if st["rep"] == 0:
            st["interval"] = 1.0
        elif st["rep"] == 1:
            st["interval"] = 6.0
        else:
            st["interval"] = round(st["interval"] * st["ef"], 1)
        st["rep"] += 1

    st["ef"] = max(
        1.3,
        st["ef"] + (0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02)),
    )
    return st


