# ---------- Показ карточки ----------
async def show_card(bot: Bot, chat_id: int, message_id: int, state: FSMContext, prefix: str = ""):
    data = await state.get_data()
    exam, subj, tid = data["exam"], data["subject"], data["topic"]
    cards = TOPICS[exam][subj][tid]["cards"]

    queue = data.get("queue")
    if queue is None:
        queue = list(range(len(cards)))
        random.shuffle(queue)

    if not queue:
        # Пользователь только что прошёл все карточки — планируем напоминание
        uid = data.get("user_id")
        if uid:
            schedule_reminder(uid, chat_id, exam, subj, tid, delay_seconds=180)

        kb = InlineKeyboardMarkup(
            inline_keyboard=[
                [InlineKeyboardButton(text="🤖 Сгенерировать ещё 3 вопроса", callback_data="gen:more")],
                [InlineKeyboardButton(text="⬅️ К темам", callback_data=f"subj:{exam}:{subj}")],
                [InlineKeyboardButton(text="🏠 В начало", callback_data="back:exam")],
            ]
        )
        text = (prefix + "\n\n━━━━━━━━━━━━\n\n" if prefix else "") + (
            "🎉 <b>Тема пройдена!</b>\n\n"
            "Все карточки на сегодня повторены. Возвращайся позже — "
            "алгоритм SM-2 подскажет, когда показать их снова."
        )
        await state.clear()
        await bot.edit_message_text(
            chat_id=chat_id, message_id=message_id, text=text,
            parse_mode="HTML", reply_markup=kb,
        )
        return

    idx = queue[0]
    card = cards[idx]
    done = len(cards) - len(queue) + 1

    await state.update_data(
        current_card_idx=idx,
        card_chat_id=chat_id,
        card_msg_id=message_id,
        queue=queue,
    )
    await state.set_state(CardFlow.waiting_answer)

    header = (prefix + "\n\n━━━━━━━━━━━━\n\n") if prefix else ""
    body = f"🎴 Карточка {done} из {len(cards)}\n\n<b>{escape(card['front'])}</b>"

    if "options" in card:
        buttons = [
            [InlineKeyboardButton(text=opt, callback_data=f"ans:{i}")]
            for i, opt in enumerate(card["options"])
        ]
    else:
        body += "\n\n✏️ <i>Напиши ответ сообщением.</i>"
        buttons = []

    buttons.append([InlineKeyboardButton(text="🤖 Спросить ИИ", callback_data="card:ai")])
    buttons.append([
        InlineKeyboardButton(text="⏭ Пропустить", callback_data="ans:skip"),
        InlineKeyboardButton(text="🏁 Закончить", callback_data="card:finish"),
    ])

    kb = InlineKeyboardMarkup(inline_keyboard=buttons)

    await bot.edit_message_text(
        chat_id=chat_id, message_id=message_id,
        text=header + body, parse_mode="HTML", reply_markup=kb,
    )


@dp.callback_query(F.data == "card:ai")
async def on_card_ai(cb: CallbackQuery, state: FSMContext):
    data = await state.get_data()
    exam, subj, tid = data.get("exam"), data.get("subject"), data.get("topic")
    idx = data.get("current_card_idx")

    if not all([exam, subj, tid]) or idx is None:
        await cb.answer("Сначала открой карточку.", show_alert=True)
        return

    card = TOPICS[exam][subj][tid]["cards"][idx]
    await cb.answer("🤖 Думаю...")

    prompt = (
        f"Тема: {TOPICS[exam][subj][tid]['title']}\n"
        f"Вопрос: {card['front']}\n"
        f"Правильный ответ: {card['answer']}\n\n"
        f"Объясни пользователю, почему это правильный ответ, простыми словами. "
        f"Если это формула — распиши её по шагам. Не пиши слишком длинно."
    )
    answer = await ask_ai(prompt)

    # Обрезаем ответ, чтобы не превысить лимиты Telegram
    safe_answer = escape(answer)
    if len(safe_answer) > 2500:
        safe_answer = safe_answer[:2500] + "\n\n... (текст обрезан)"

    # 1. Начисляем "провал" в SM-2
    user_id = data.get("user_id")
    key = (user_id, exam, subj, tid, idx)
    st = CARD_STATES.get(key, {"rep": 0, "interval": 1.0, "ef": 2.5})
    sm2_update(st, 1)  # 1 = провал
    CARD_STATES[key] = st

    # 2. Двигаем очередь (убираем текущую, кидаем в конец)
    queue = data.get("queue") or []
    queue = queue[1:]
    queue.append(idx)
    await state.update_data(queue=queue)

    # 3. Показываем ТОЛЬКО объяснение и новые кнопки
    text = (
        f"🤖 <b>Объяснение ИИ:</b>\n\n{safe_answer}\n\n"
        f"━━━━━━━━━━━━\n"
        f"❌ <i>Карточка засчитана как проваленная и будет показана позже.</i>"
    )

    kb = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="▶️ Следующая карточка", callback_data="card:next")],
        [InlineKeyboardButton(text="🏁 Закончить", callback_data="card:finish")]
    ])

    await cb.message.edit_text(text, parse_mode="HTML", reply_markup=kb)
