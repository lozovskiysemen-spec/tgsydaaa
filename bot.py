@dp.message(CardFlow.waiting_answer, F.text)
async def on_text_answer(msg: Message, state: FSMContext):
    data = await state.get_data()
    exam, subj, tid = data["exam"], data["subject"], data["topic"]
    idx = data["current_card_idx"]
    card = TOPICS[exam][subj][tid]["cards"][idx]

    if "options" in card:
        await msg.answer("Пожалуйста, выбери вариант кнопкой 👇")
        return

    user_text = msg.text.strip()
    user_lower = user_text.lower()
    correct_answers = [card["answer"].lower()] + [a.lower() for a in card.get("aliases", [])]
    correct = user_lower in correct_answers
    quality = 4 if correct else 1

    try:
        await msg.delete()
    except Exception:
        pass

    await process_answer(msg.bot, state, correct=correct, user_answer=user_text, quality=quality)


